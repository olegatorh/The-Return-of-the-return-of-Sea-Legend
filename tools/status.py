#!/usr/bin/env python3
"""Generates docs/STATUS.md from docs/status_data.txt (ratings kept by hand) plus numbers measured from the repository.
Run:  python tools/status.py   (edit docs/status_data.txt when something changes, then re-run)"""
import re, datetime, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
rows = []
for line in (root / 'docs/status_data.txt').read_text(encoding='utf-8').splitlines():
    if not line.strip() or line.startswith('#'):
        continue
    p = [x.strip() for x in line.split('|')] + [''] * 6
    rows.append(dict(area=p[0], item=p[1], layer=p[2], acc=int(p[3]), how=p[4], notes=p[5]))
areas = [r for r in rows if r['area'] != 'Entity class']
classes = [r for r in rows if r['area'] == 'Entity class']


def source_files(folder):
    for f in (root / folder).rglob('*.cs'):
        if not any(x in f.parts for x in ('bin', 'obj', '.godot')):
            yield f


tests = sum(len(re.findall(r'\[Fact\]', f.read_text(encoding='utf-8', errors='ignore'))) for f in source_files('StormScript.Tests'))
loc = sum(len(f.read_text(encoding='utf-8', errors='ignore').splitlines()) for d in ('game', 'StormScript') for f in source_files(d))
api = ''
try:
    api = (root / 'docs/engine_api.txt').read_text(encoding='utf-8', errors='ignore').splitlines()[0].lstrip('# ')
except Exception:
    pass

layers = ['SCRIPT', 'NATIVE', 'PORT', 'APPROX', 'STUB', 'MISSING']
desc = {'SCRIPT': 'original script, interpreted unchanged', 'NATIVE': 'original data file read directly',
        'PORT': 're-implemented from the engine contract (close to the original)', 'APPROX': 'own approximation of the original behaviour',
        'STUB': 'accepted by the port but has no effect', 'MISSING': 'not implemented'}


def avg(rs):
    return round(sum(r['acc'] for r in rs) / len(rs)) if rs else 0


total = avg(areas)
out = ['# Port status: what is interpreted, native, re-implemented, approximated', '',
       f'_Generated by `tools/status.py` on {datetime.date.today()} from `docs/status_data.txt` (ratings kept by hand) and the repository. Do not edit this file._', '',
       '## How to read it', '', 'Layers (where the behaviour comes from):', '']
out += [f'* **{l}**: {desc[l]}' for l in layers]
out += ['', '**Accuracy** = how close the result is to the original game, 0-100 %. How it was obtained: **T** automated test, **V** visual comparison with screenshots / the expected look, '
        '**E** estimate (no measurement yet). A rating is a judgement, not a benchmark; the notes say what is missing.', '', '## Summary', '',
        f'* Overall (mean of the {len(areas)} subsystems below): **{total} %**',
        f'* Unit tests: **{tests}** (plus the game scenarios of `run_tests.ps1 -Smoke / -Intro / -Sea`)',
        f'* Port code: **{loc}** lines of C# (`StormScript/` library + `game/`)']
if api:
    out.append(f'* Original scripts: {api}')
out += ['', '| Layer | Subsystems | Mean accuracy |', '|---|---|---|']
for l in layers:
    rs = [r for r in areas if r['layer'] == l]
    out.append(f'| {l} | {len(rs)} | {avg(rs)} % |')
out += ['', '## Subsystems', '', '| Area | Item | Layer | Accuracy | By | Notes |', '|---|---|---|---|---|---|']
for r in areas:
    bar = '█' * (r['acc'] // 10) + '░' * (10 - r['acc'] // 10)
    out.append(f"| {r['area']} | {r['item']} | {r['layer']} | {bar} {r['acc']} % | {r['how']} | {r['notes']} |")
out += ['', f'## Engine classes that the scripts create ({len(classes)})', '',
        'The scripts talk to the engine only through `CreateEntity(&obj, "class")`, `SendMessage(&obj, ...)`, events and a few native functions (`docs/engine_surface.txt`).', '',
        '| Layer | Count | Classes |', '|---|---|---|']
for l in layers:
    rs = [r for r in classes if r['layer'] == l]
    if rs:
        out.append(f"| {l} | {len(rs)} | " + ', '.join('`' + r['item'] + '`' + (f" ({r['acc']}%)" if r['acc'] else '') for r in rs) + ' |')
done = [r for r in classes if r['layer'] in ('PORT', 'APPROX')]
out += ['', f"Classes with real behaviour: **{len(done)} of {len(classes)}** ({round(100 * len(done) / max(1, len(classes)))} %); stubs: {len([r for r in classes if r['layer'] == 'STUB'])}, missing: {len([r for r in classes if r['layer'] == 'MISSING'])}.",
        '', '## How accuracy is checked (and what is still unchecked)', '',
        '* **Interpreter**: unit tests per semantic rule (`StormScript.Tests/InterpreterTests.cs`) and a headless boot of the whole game (`ScriptCorpusTests`). Every interpreter bug gets a test.',
        '* **Scenarios**: `run_tests.ps1 -Smoke | -Intro | -Sea` run the real game and fail on script errors, unresolved engine functions and missing expected log lines.',
        '* **Visual**: screenshots from the port compared by eye with the expected look of the original (no automatic image diff yet).',
        '* **Not measured yet**: frame timing, physics values against the original binary, translation quality, AI behaviour parity. Those ratings are estimates (E).',
        '', '## Updating', '', '1. Change a row in `docs/status_data.txt` when a subsystem moves (for example `APPROX | 50` to `PORT | 80`).',
        '2. Run `python tools/status.py`.', '3. Commit both files.']
(root / 'docs/STATUS.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'docs/STATUS.md written: overall {total} %, {len(classes)} classes, {tests} tests, {loc} lines')
