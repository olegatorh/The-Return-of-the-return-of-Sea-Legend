path = sys.argv[1]
existing = {}
order = []
for line in open(path, encoding='utf-8').read().split('\n'):
    if '\t' in line:
        k, v = line.split('\t', 1)
        existing[k] = v
        order.append(k)
n = 0
for k, v in PAIRS.items():
    if existing.get(k) != v:
        if k not in existing:
            order.append(k)
        existing[k] = v
        n += 1
with open(path, 'w', encoding='utf-8') as f:
    for k in order:
        f.write(f'{k}\t{existing[k]}\n')
print('entries set:', n, 'total:', len(existing))
